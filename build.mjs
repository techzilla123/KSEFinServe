/* Build helper.
   Vite inlines every VITE_-prefixed env var into the client bundle, which
   leaks the Gemini key into dist/ and trips GitHub push protection. Instead we
   write public/config.js from .env before Vite runs, and the app reads it at
   runtime. Run directly with `node build.mjs`; `npm run build` calls it. */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { spawnSync } from "node:child_process"

const root = join(dirname(fileURLToPath(import.meta.url)))
const envPath = join(root, ".env")
const outDir = join(root, "public")
const outFile = join(outDir, "config.js")

/** Parse KEY=value lines out of .env, ignoring comments and blanks. */
function readEnvFile(path) {
  if (!existsSync(path)) return {}
  const values = {}
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith("#")) continue
    const eq = trimmed.indexOf("=")
    if (eq === -1) continue
    const key = trimmed.slice(0, eq).trim()
    const value = trimmed.slice(eq + 1).trim().replace(/^["']|["']$/g, "")
    if (key) values[key] = value
  }
  return values
}

const env = readEnvFile(envPath)

/** Only the values the browser is allowed to see. */
const publicConfig = {
  geminiApiKey: env.VITE_GEMINI_API_KEY ?? "",
  supabaseUrl: env.VITE_SUPABASE_URL ?? "",
  supabaseAnonKey: env.VITE_SUPABASE_ANON_KEY ?? "",
}

mkdirSync(outDir, { recursive: true })
writeFileSync(
  outFile,
  `/* Generated by build.mjs — do not edit by hand.\n` +
    `   Exposes non-secret runtime configuration to the browser. */\n` +
    `window.__KSE_CONFIG__ = ${JSON.stringify(publicConfig, null, 2)};\n`,
)

console.log(`build.mjs: wrote public/config.js (geminiApiKey ${publicConfig.geminiApiKey ? "present" : "absent"})`)

const viteBin = join(root, "node_modules", ".bin", "vite")
const result = spawnSync(viteBin, ["build"], { cwd: root, stdio: "inherit", shell: true })
process.exit(result.status ?? 1)
