/* Build helper.
   Vite inlines every VITE_-prefixed env var into the client bundle, which
   leaks secrets into dist/ and trips GitHub push protection and Netlify's
   secrets scan. Instead we write a small config.js from the environment before
   Vite runs, and the app reads it at runtime.

   Values are read from process.env first (Netlify/Vercel set these at build
   time) and fall back to .env for local builds.

   config.js is written directly into dist/ as well as public/, so the file is
   present in the published site even when the host checks out the repo and
   serves a pre-built dist/ without running the build.

   Run directly with `node build.mjs`; `npm run build` calls it. */

import { readFileSync, writeFileSync, existsSync, mkdirSync, rmSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { spawnSync } from "node:child_process"

const root = join(dirname(fileURLToPath(import.meta.url)))
const envPath = join(root, ".env")

/** Parse KEY=value lines out of .env, ignoring comments and blanks. */
function readEnvFile(path) {
  if (!existsSync(path)) return {}
  const values = {}
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith("#")) continue
    const eq = trimmed.indexOf("=")
    if (eq === -1) continue
    const key = trimmed.slice(0, eq).trim()
    const value = trimmed.slice(eq + 1).trim().replace(/^["']|["']$/g, "")
    if (key) values[key] = value
  }
  return values
}

const fileEnv = readEnvFile(envPath)

/**
 * Resolve a config value: the build environment wins, .env is the local
 * fallback. Netlify injects VITE_-prefixed vars into process.env at build time.
 */
function resolve(key) {
  return process.env[key] ?? fileEnv[key] ?? ""
}

/** Only the values the browser is allowed to see.
    The service-role key is deliberately absent — it never leaves the server. */
const publicConfig = {
  geminiApiKey: resolve("VITE_GEMINI_API_KEY"),
  supabaseUrl: resolve("VITE_SUPABASE_URL"),
  supabaseAnonKey: resolve("VITE_SUPABASE_ANON_KEY"),
}

const configJs =
  `/* Generated by build.mjs — do not edit by hand.\n` +
  `   Exposes non-secret runtime configuration to the browser. */\n` +
  `window.__KSE_CONFIG__ = ${JSON.stringify(publicConfig, null, 2)};\n`

const distDir = join(root, "dist")

const missing = Object.entries(publicConfig)
  .filter(([, v]) => !v)
  .map(([k]) => k)

console.log(
  `build.mjs: wrote config.js ` +
    `(geminiApiKey ${publicConfig.geminiApiKey ? "present" : "ABSENT"}, ` +
    `supabaseUrl ${publicConfig.supabaseUrl ? "present" : "ABSENT"}, ` +
    `supabaseAnonKey ${publicConfig.supabaseAnonKey ? "present" : "ABSENT"})`,
)
if (missing.length) {
  console.warn(
    `build.mjs: WARNING — no value for ${missing.join(", ")}. ` +
      `Set them as build-time environment variables.`,
  )
}

// Start from a clean dist so stale hashed bundles cannot linger.
rmSync(distDir, { recursive: true, force: true })

const viteBin = join(root, "node_modules", ".bin", "vite")
const result = spawnSync(viteBin, ["build"], { cwd: root, stdio: "inherit", shell: true })

// Vite copies public/config.js (the committed placeholder) into dist/. Replace
// it with the populated version now, after the build, so the keys never touch
// public/ or version control.
if (result.status === 0) {
  mkdirSync(distDir, { recursive: true })
  writeFileSync(join(distDir, "config.js"), configJs)
  // Local dev: Vite serves public/, so the populated copy goes there too.
  // public/config.js holds the committed placeholder and is left untouched.
  writeFileSync(join(root, "public", "config.local.js"), configJs)
  console.log("build.mjs: wrote dist/config.js and public/config.local.js")
}

process.exit(result.status ?? 1)
